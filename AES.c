static uint8_t rk[176];

static uint8_t xt(uint8_t x) { return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1b : 0)); }
static uint8_t mul(uint8_t a, uint8_t b) {
    uint8_t r=0;
    while (b) { if (b&1) r^=a; a=xt(a); b>>=1; }
    return r;
}
static void expand(const uint8_t *key) {
    int i, j; uint8_t t[4], rc=1;
    for (i=0;i<16;i++) rk[i]=key[i];
    for (i=16;i<176;i+=4) {
        for(j=0;j<4;j++) t[j]=rk[i-4+j];
        if (i%16==0) {
            uint8_t z=t[0]; t[0]=sbox[t[1]]^rc; t[1]=sbox[t[2]];
            t[2]=sbox[t[3]]; t[3]=sbox[z]; rc=xt(rc);
        }
        for(j=0;j<4;j++) rk[i+j]=rk[i-16+j]^t[j];
    }
}
static void add(uint8_t *s,int round) { int i; for(i=0;i<16;i++) s[i]^=rk[round*16+i]; }
static void sub(uint8_t *s) { int i; for(i=0;i<16;i++) s[i]=sbox[s[i]]; }
static void isub(uint8_t *s) { int i; for(i=0;i<16;i++) s[i]=invs[s[i]]; }
static void shift(uint8_t *s) {
    uint8_t t[16]; int r,c;
    for(r=0;r<4;r++) for(c=0;c<4;c++) t[r+4*c]=s[r+4*((c+r)%4)];
    memcpy(s,t,16);
}
static void ishift(uint8_t *s) {
    uint8_t t[16]; int r,c;
    for(r=0;r<4;r++) for(c=0;c<4;c++) t[r+4*c]=s[r+4*((c-r+4)%4)];
    memcpy(s,t,16);
}
static void mix(uint8_t *s) {
    int c; for(c=0;c<4;c++) {
        uint8_t *a=s+4*c, x=a[0]^a[1]^a[2]^a[3], t=a[0];
        a[0]^=x^xt(a[0]^a[1]); a[1]^=x^xt(a[1]^a[2]);
        a[2]^=x^xt(a[2]^a[3]); a[3]^=x^xt(a[3]^t);
    }
}
static void imix(uint8_t *s) {
    int c; for(c=0;c<4;c++) {
        uint8_t *a=s+4*c, x=a[0],y=a[1],z=a[2],w=a[3];
        a[0]=mul(x,14)^mul(y,11)^mul(z,13)^mul(w,9);
        a[1]=mul(x,9)^mul(y,14)^mul(z,11)^mul(w,13);
        a[2]=mul(x,13)^mul(y,9)^mul(z,14)^mul(w,11);
        a[3]=mul(x,11)^mul(y,13)^mul(z,9)^mul(w,14);
    }
}
static void encrypt(uint8_t *s) {
    int r; add(s,0);
    for(r=1;r<10;r++){sub(s);shift(s);mix(s);add(s,r);}
    sub(s);shift(s);add(s,10);
}
static void decrypt(uint8_t *s) {
    int r; add(s,10);
    for(r=9;r>0;r--){ishift(s);isub(s);add(s,r);imix(s);}
    ishift(s);isub(s);add(s,0);
}
